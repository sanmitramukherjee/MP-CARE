"""MP-CARE launch: network model + N MP-CARE agents + logger (plan §3.2).

Two modes, selected with `use_gazebo` (each gz-related action carries an
IfCondition, evaluated by ros2 launch at RUNTIME — CLI overrides work):

  use_gazebo:=false  (DEFAULT — Tier 1, no Gazebo needed)
      Start the MP-CARE side only and INJECT odometry by hand, e.g.:

      ros2 topic pub -r 10 /uav_0/odom nav_msgs/msg/Odometry \
        '{pose: {pose: {position: {x: 0.0, y: 0.0, z: 40.0}}}}'
      ros2 topic pub -r 10 /uav_1/odom nav_msgs/msg/Odometry \
        '{pose: {pose: {position: {x: 200.0, y: 0.0, z: 40.0}}}}'
      # ... up to /uav_4 at x = 800.0 (the 4-hop chain geometry)

  use_gazebo:=true   (Tier 3)
      Also start `gz sim` with the chosen world, spawn N STATIC uav_probe
      models (each publishing ground-truth odometry via OdometryPublisher),
      and bridge /model/uav_probe_<i>/odometry -> /uav_i/odom. The probes
      do NOT fly — controlled geometry on purpose
      (see worlds/models/uav_probe/model.sdf).

Scale runs (Phase 6/7 gate): n_uav:=50 with the canonical v3 topology:

    ros2 launch launch/mpcare_sim.launch.py use_gazebo:=true n_uav:=50 \
        world:=scale_field spawn_csv:=data/raw/phase6_dev/gazebo_n50_positions.csv \
        trial_id:=gazebo_n50
    (positions generated by scripts/gen_gazebo_positions.py — the REAL
    campaign scenario builder, seed 3001: measured t=0 degree 8.00, 50/50
    src-dst connected)

Run from the REPOSITORY ROOT (parameter paths are cwd-relative):

    colcon build --symlink-install && source install/setup.bash
    ros2 launch launch/mpcare_sim.launch.py trial_id:=ubuntu_tier1
    ros2 launch launch/mpcare_sim.launch.py use_gazebo:=true trial_id:=ubuntu_tier3

Requires ROS 2 Lyrical on Ubuntu 26.04 + Gazebo Jetty (NOTES/testROS2.md).
"""

import csv
import os
import shlex

from launch import LaunchDescription
from launch.actions import (DeclareLaunchArgument, ExecuteProcess,
                            OpaqueFunction, SetEnvironmentVariable,
                            TimerAction)
from launch.conditions import IfCondition
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node

SPACING_M = 200.0      # default row layout: 2-hop distance 400 m > 300 m
WORLD_DEFAULT = "open_field"


def _use_gz():
    return IfCondition(LaunchConfiguration("use_gazebo"))


def _spawn_positions(n_uav: int, spawn_csv: str) -> list[tuple[float, float, float]]:
    """Probe spawn positions: from the campaign-topology CSV when given
    (columns uav_id,x_m,y_m,z_m; exactly n_uav rows required), else the
    historical 200 m row."""
    if spawn_csv:
        rows = list(csv.DictReader(open(spawn_csv, encoding="utf-8")))
        if len(rows) != n_uav:
            raise ValueError(
                f"spawn_csv has {len(rows)} rows but n_uav={n_uav}")
        out = []
        for r in sorted(rows, key=lambda r: int(r["uav_id"])):
            out.append((float(r["x_m"]), float(r["y_m"]), float(r["z_m"])))
        return out
    return [(i * SPACING_M, 0.0, 0.5) for i in range(n_uav)]


def _spawn_probe(i: int, xy: tuple[float, float, float]) -> ExecuteProcess:
    """Spawn uav_probe_<i> via ros_gz_sim create — the Jetty-native way.
    (A raw `gz service` request with a `file:` field FAILS on Jetty:
    gz.msgs.EntityFactory has no `file` field anymore — `create` reads the
    model file and injects the SDF string itself.)"""
    return ExecuteProcess(
        cmd=["ros2", "run", "ros_gz_sim", "create",
             "-file", os.path.join("worlds", "models", "uav_probe", "model.sdf"),
             "-name", f"uav_probe_{i}",
             "-x", f"{xy[0]:.3f}", "-y", f"{xy[1]:.3f}", "-z", f"{xy[2]:.3f}"],
        output="screen", condition=_use_gz())


def _bridge(i: int) -> Node:
    """Gazebo -> ROS odometry bridge for probe i."""
    return Node(
        package="ros_gz_bridge", executable="parameter_bridge",
        name=f"odom_bridge_{i}",
        arguments=[f"/model/uav_probe_{i}/odometry"
                   "@nav_msgs/msg/Odometry[gz.msgs.Odometry"],
        remappings=[(f"/model/uav_probe_{i}/odometry", f"/uav_{i}/odom")],
        output="screen", condition=_use_gz())


def _setup(context, *args, **kwargs):
    """OpaqueFunction body: the per-UAV loops need the PARSED n_uav and the
    spawn CSV at launch-eval time (LaunchConfiguration substitutions cannot
    drive `range()` — Phase 7's N=50 gate needs real loops)."""
    n_uav = int(LaunchConfiguration("n_uav").perform(context))
    spawn_csv = LaunchConfiguration("spawn_csv").perform(context).strip()
    world = LaunchConfiguration("world").perform(context).strip()
    gz_args = LaunchConfiguration("gz_args").perform(context).strip()
    gz_external = LaunchConfiguration("gz_external").perform(context) in (
        "1", "true", "True")
    trial_id = LaunchConfiguration("trial_id")
    out_dir = LaunchConfiguration("out_dir")

    models_path = os.path.abspath(os.path.join("worlds", "models"))
    gz_resource = (models_path + os.pathsep + os.environ.get(
        "GZ_SIM_RESOURCE_PATH", ""))

    positions = _spawn_positions(n_uav, spawn_csv)

    agents = [
        Node(
            package="mpcare_agent", executable="planner_node",
            name=f"mpcare_agent_{i}", output="screen",
            parameters=["config/mpcare_agent.yaml",
                        {"uav_id": i, "n_uav": n_uav}],
        ) for i in range(n_uav)]

    return [
        # let `file: 'uav_probe'` resolve to worlds/models/uav_probe
        SetEnvironmentVariable("GZ_SIM_RESOURCE_PATH", gz_resource),

        # ---- Tier 3 only: simulator + spawns + delayed bridges ----
        # gz_external:=true skips the in-launch server (scripts/gz50_server.sh
        # starts it standalone first; `create` stalls against a COLD server —
        # measured, see the launch docstring).
        *([] if gz_external else [ExecuteProcess(
            cmd=["gz", "sim", "-r"]
                + (shlex.split(gz_args) if gz_args else [])
                + [f"worlds/{world}.sdf"],
            output="screen", condition=_use_gz())]),
        # spawns AND bridges are delayed: `create` against a COLD server
        # races the world load (N=50 gate evidence: fresh-world runs wrote
        # header-only CSVs — no models, no odometry, no telemetry — while a
        # run against an already-serving world streamed 13.6k rows). 5 s in,
        # the SceneBroadcaster is serving; bridges go last (topic bridges
        # attach lazily, but late is safer than early).
        TimerAction(period=5.0,
                    actions=[_spawn_probe(i, positions[i])
                             for i in range(n_uav)],
                    condition=_use_gz()),
        TimerAction(period=max(10.0, 0.2 * n_uav),
                    actions=[_bridge(i) for i in range(n_uav)],
                    condition=_use_gz()),

        # ---- both modes: the MP-CARE side (plan §3.2) ----
        Node(
            package="network_model", executable="network_model_node",
            name="network_model", output="screen",
            parameters=["config/network_model.yaml", {"n_uav": n_uav}],
        ),
        *agents,
        Node(
            package="logger", executable="logger_node",
            name="swarm_logger", output="screen",
            parameters=["config/logger.yaml",
                        {"trial_id": trial_id, "out_dir": out_dir,
                         "experiment": "phase4_ros", "algorithm": "mpcare"}],
        ),
    ]


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument("n_uav", default_value="5"),
        DeclareLaunchArgument("trial_id", default_value=""),
        DeclareLaunchArgument("out_dir", default_value="data/raw"),
        DeclareLaunchArgument("use_gazebo", default_value="false",
                              description="Tier 3: start gz sim + probes + bridges"),
        DeclareLaunchArgument("world", default_value=WORLD_DEFAULT,
                              description="world file under worlds/ "
                                          "(scale runs: scale_field)"),
        DeclareLaunchArgument("spawn_csv", default_value="",
                              description="optional CSV (uav_id,x_m,y_m,z_m) "
                                          "with exactly n_uav probe "
                                          "positions; default = 200 m row"),
        DeclareLaunchArgument("gz_args", default_value="",
                              description="extra gz sim args, e.g. -s for a "
                                          "headless SERVER-only run (gates/CI)"),
        DeclareLaunchArgument("gz_external", default_value="false",
                              description="skip the in-launch gz server (a "
                                          "server started separately is "
                                          "already serving)"),
        OpaqueFunction(function=_setup),
    ])
